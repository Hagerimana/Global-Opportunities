"""Generate Django .po and .mo catalogues from the project translation data.

There is no xgettext/msgfmt/polib/babel dependency in this environment. This
script pulls every gettext message id straight from the Python source with an
AST walk, checks the hand-written translations in ``locale/messages-*.json``,
and writes compilable Gettext binaries itself.
"""

from __future__ import annotations

import json
import struct
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from extract_messages import ROOTS, extract_from_file  # noqa: E402

LOCALES = ("fr", "rn", "sw")
BASE = Path(__file__).resolve().parents[1]
LOCALE_DIR = BASE / "locale"


def load_translations() -> dict[str, dict[str, str]]:
    translations: dict[str, dict[str, str]] = {}
    for path in sorted(LOCALE_DIR.glob("messages-*.json")):
        data = json.loads(path.read_text(encoding="utf-8"))
        for msgid, values in data.items():
            if msgid in translations:
                raise SystemExit(f"Duplicate msgid across translation files: {msgid!r}")
            missing = set(LOCALES) - set(values)
            if missing:
                raise SystemExit(
                    f"{msgid!r} is missing translations: {', '.join(sorted(missing))}"
                )
            translations[msgid] = values
    return translations


def collect_msgids() -> dict[str, list[str]]:
    msgids: dict[str, list[str]] = {}
    for root_name in ROOTS:
        base = BASE / root_name
        if not base.exists():
            continue
        for path in sorted(base.rglob("*.py")):
            relative = path.relative_to(BASE).as_posix()
            for line, text in extract_from_file(path):
                msgids.setdefault(text, []).append(f"{relative}:{line}")
    return msgids


def placeholders(text: str) -> set[str]:
    """Return the set of ``str.format`` fields used by a message."""

    fields: set[str] = set()
    index = 0
    while index < len(text):
        if text[index] == "{":
            if text.startswith("{{", index):
                index += 2
                continue
            close = text.find("}", index + 1)
            if close == -1:
                raise ValueError(f"Unclosed placeholder in {text!r}")
            fields.add(text[index + 1 : close])
            index = close + 1
        else:
            index += 1
    return fields


def po_escape(text: str) -> str:
    return (
        text.replace("\\", "\\\\")
        .replace('"', '\\"')
        .replace("\n", "\\n")
        .replace("\t", "\\t")
        .replace("\r", "\\r")
    )


def write_po(locale: str, messages: dict[str, str]) -> Path:
    header = [
        "# Global Opportunities backend translations.",
        "# This file is generated by backend/tools/compile_messages.py.",
        'msgid ""',
        'msgstr ""',
        f'"Language: {locale}\\n"',
        '"MIME-Version: 1.0\\n"',
        '"Content-Type: text/plain; charset=UTF-8\\n"',
        '"Content-Transfer-Encoding: 8bit\\n"',
        '"Plural-Forms: nplurals=2; plural=(n > 1);\\n"',
        "",
    ]
    lines = header
    for msgid in sorted(messages):
        lines.append(f'msgid "{po_escape(msgid)}"')
        lines.append(f'msgstr "{po_escape(messages[msgid])}"')
        lines.append("")

    target = LOCALE_DIR / locale / "LC_MESSAGES" / "django.po"
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    return target


def write_mo(locale: str, messages: dict[str, str]) -> Path:
    metadata = f"""Project-Id-Version: Global Opportunities
Language: {locale}
MIME-Version: 1.0
Content-Type: text/plain; charset=UTF-8
Content-Transfer-Encoding: 8bit
Plural-Forms: nplurals=2; plural=(n > 1);
"""
    entries = [("", metadata)]
    entries.extend(sorted(messages.items()))

    encoded = [
        (msgid.encode("utf-8"), translation.encode("utf-8"))
        for msgid, translation in entries
    ]

    count = len(encoded)
    key_table_offset = 28
    value_table_offset = key_table_offset + 8 * count
    string_offset = value_table_offset + 8 * count

    key_table = bytearray()
    value_table = bytearray()
    payload = bytearray()

    for msgid, _translation in encoded:
        key_table.extend(struct.pack("<II", len(msgid), string_offset + len(payload)))
        payload.extend(msgid)
        payload.append(0)

    for _msgid, translation in encoded:
        value_table.extend(
            struct.pack("<II", len(translation), string_offset + len(payload))
        )
        payload.extend(translation)
        payload.append(0)

    output = bytearray()
    output.extend(
        struct.pack(
            "<Iiiiiii",
            0x950412DE,
            0,
            count,
            key_table_offset,
            value_table_offset,
            0,
            0,
        )
    )
    output.extend(key_table)
    output.extend(value_table)
    output.extend(payload)

    target = LOCALE_DIR / locale / "LC_MESSAGES" / "django.mo"
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_bytes(bytes(output))
    return target


def main() -> int:
    translations = load_translations()
    msgids = collect_msgids()

    unknown = sorted(set(translations) - set(msgids))
    missing = sorted(set(msgids) - set(translations))

    problems: list[str] = []
    for msgid in missing:
        problems.append(f"Missing translation: {msgid!r}")
    for msgid, values in translations.items():
        expected = placeholders(msgid)
        for locale, value in values.items():
            actual = placeholders(value)
            if expected != actual:
                problems.append(
                    f"Placeholder mismatch for {locale} {msgid!r}: "
                    f"expected {sorted(expected)}, found {sorted(actual)}"
                )

    if unknown:
        print(f"Warning: {len(unknown)} translation entries are not referenced:")
        for msgid in unknown:
            print(f"  {msgid!r}")

    if problems:
        print(f"{len(problems)} problem(s) found:")
        for problem in problems:
            print(f"  {problem}")
        return 1

    for locale in LOCALES:
        messages = {
            msgid: values[locale]
            for msgid, values in translations.items()
            if msgid in msgids
        }
        po_path = write_po(locale, messages)
        mo_path = write_mo(locale, messages)
        print(f"{locale}: {len(messages)} messages -> {po_path.name}, {mo_path.name}")

    print(f"{len(msgids)} source message ids; {len(translations)} translations.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
